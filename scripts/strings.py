#!/usr/bin/env python3
"""Collects PixlSnapz's user-facing strings into the translators' template,
macos/en.lproj/Localizable.strings, and checks the translations.

Usage: python3 -I scripts/strings.py [--check]

Strings are the literals in t!(...), n!(...) and tr(...), and the titles
passed to the menu helpers (item, check, submenu) and the Settings helpers
(checkbox, button, .row); and in the Shortcuts actions
(macos/intents/*.swift), the titles, descriptions, and names App Intents
shows, which it looks up in the same Localizable.strings. With --check, nothing is written: it fails when
the template is out of date, or when a translation in macos/<language>.lproj
is missing a string, has an empty one, or changes a string's {placeholders}.
To add a language: copy the template to macos/<language>.lproj, translate
the values (never the keys), and add the language to CFBundleLocalizations
in macos/Info.plist.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "macos/en.lproj/Localizable.strings"
LITERAL = r'"((?:[^"\\]|\\.)*)"'
PATTERNS = [
    re.compile(r"\b(?:t|n)!\(\s*" + LITERAL, re.S),
    re.compile(r"\btr\(\s*" + LITERAL, re.S),
    re.compile(r"\b(?:item|check|submenu)\(\s*&?[\w.]+\s*,\s*" + LITERAL, re.S),
    re.compile(r"\b(?:checkbox|button)\(\s*" + LITERAL, re.S),
    re.compile(r"\.row\(\s*" + LITERAL, re.S),
]
# App Intents' localized strings: titles, descriptions, parameter titles,
# enum case names, and short titles.
SWIFT_PATTERNS = [
    re.compile(r"LocalizedStringResource\s*=\s*" + LITERAL),
    re.compile(r"TypeDisplayRepresentation\s*=\s*" + LITERAL),
    re.compile(r"IntentDescription\(\s*" + LITERAL),
    re.compile(r"\b(?:title|description|shortTitle):\s*" + LITERAL),
    re.compile(r"^\s*\.\w+:\s*" + LITERAL, re.M),
]
PLACEHOLDER = re.compile(r"(?<!\{)\{(\w+)\}(?!\})")


def unescape(rust: str) -> str:
    """The value of a Rust string literal's contents."""
    rust = re.sub(r"\\\n\s*", "", rust)  # line continuation
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), rust)


def escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def collect() -> dict[str, list[str]]:
    """Each string, with the files that use it."""
    found: dict[str, list[str]] = {}
    for path in sorted((ROOT / "src").rglob("*.rs")):
        source = path.read_text()
        # Leave out test modules: their strings are not shown to anyone.
        cut = source.find("#[cfg(test)]")
        if cut >= 0:
            source = source[:cut]
        for pattern in PATTERNS:
            for match in pattern.finditer(source):
                text = unescape(match.group(1))
                if not text.strip() or not re.search(r"[A-Za-z]", text):
                    continue
                # File names only: line numbers would make every edit stale.
                found.setdefault(text, []).append(str(path.relative_to(ROOT)))
    for path in sorted((ROOT / "macos/intents").glob("*.swift")):
        source = path.read_text()
        for pattern in SWIFT_PATTERNS:
            for match in pattern.finditer(source):
                text = unescape(match.group(1))
                if text.strip() and "\\(" not in match.group(1):
                    found.setdefault(text, []).append(str(path.relative_to(ROOT)))
    return found


def template(found: dict[str, list[str]]) -> str:
    out = [
        "/* PixlSnapz's user-facing text: the template for translations.",
        "   Generated by scripts/strings.py from the source; do not edit by hand.",
        "   To translate: copy this file to macos/<language>.lproj/Localizable.strings",
        "   and translate the values (on the right), never the keys. Keep every",
        "   {placeholder}: it is filled in with a value, and may move. */",
        "",
    ]
    for text in sorted(found, key=str.lower):
        out.append(f"/* {', '.join(sorted(set(found[text])))} */")
        out.append(f'"{escape(text)}" = "{escape(text)}";')
        out.append("")
    return "\n".join(out)


def parse(path: Path) -> dict[str, str]:
    """The key-value pairs of a .strings file."""
    text = re.sub(r"/\*.*?\*/", "", path.read_text(), flags=re.S)
    pairs = {}
    for match in re.finditer(LITERAL + r"\s*=\s*" + LITERAL + r"\s*;", text):
        key, value = (re.sub(r"\\(.)", lambda m: {"n": "\n"}.get(m.group(1), m.group(1)), g) for g in match.groups())
        pairs[key] = value
    return pairs


def main() -> int:
    check = "--check" in sys.argv[1:]
    found = collect()
    wanted = template(found)
    problems = []
    if check:
        if not TEMPLATE.exists() or TEMPLATE.read_text() != wanted:
            problems.append(f"{TEMPLATE.relative_to(ROOT)} is out of date: run python3 -I scripts/strings.py")
    else:
        TEMPLATE.parent.mkdir(parents=True, exist_ok=True)
        TEMPLATE.write_text(wanted)
        print(f"Wrote {TEMPLATE.relative_to(ROOT)} ({len(found)} strings)")
    for path in sorted((ROOT / "macos").glob("*.lproj/Localizable.strings")):
        if path.parent.name == "en.lproj":
            continue
        language = path.parent.name.removesuffix(".lproj")
        translated = parse(path)
        for key in found:
            value = translated.get(key)
            if value is None:
                problems.append(f"{language}: missing {key!r}")
            elif not value.strip():
                problems.append(f"{language}: empty translation of {key!r}")
            elif set(PLACEHOLDER.findall(key)) != set(PLACEHOLDER.findall(value)):
                problems.append(f"{language}: placeholders differ in {key!r}: {value!r}")
        for key in translated:
            if key not in found:
                problems.append(f"{language}: not used anymore: {key!r}")
        print(f"{language}: {len(translated)} strings")
    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
